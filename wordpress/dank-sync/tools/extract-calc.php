<?php
/**
 * Copies the account calculation out of the dank.capital theme into the plugin,
 * unchanged, so the app gets exactly the figures the site's account page shows.
 *
 *   php wordpress/dank-sync/tools/extract-calc.php wordpress/theme-src/hello-theme-dank
 *
 * Writes includes/account-calc.php (the code) and includes/theme-fingerprint.php
 * (hashes of the theme files it came from; the plugin warns when they change).
 * Re-run it whenever the theme's account template changes.
 */

[$_, $themeDir] = $argv + [null, null];
if (!$themeDir || !is_dir($themeDir)) {
    fwrite(STDERR, "usage: php extract-calc.php <path to hello-theme-dank>\n");
    exit(1);
}

$templateFile  = "$themeDir/account-template.php";
$variablesFile = "$themeDir/inc/variables.php";
$functionsFile = "$themeDir/inc/functions-to-use.php";

// 1. inc/variables.php, included by the template before the calculation.
// Only change: the investor is passed in instead of read from the session.
$variables = file_get_contents($variablesFile);
$variables = preg_replace('/^<\?php\s*/', '', $variables, 1, $count);
must($count === 1, 'variables.php: opening tag');
$variables = str_replace('$current_user = wp_get_current_user();', '/* $current_user is passed in by DankSync\Account\calculate() */', $variables, $count);
must($count === 1, 'variables.php: wp_get_current_user() line');

// 2. The calculation block of account-template.php: from the first totals
// line to the end of the referral loop, right before the page markup.
$template = file_get_contents($templateFile);
$start = strpos($template, '/*and total current capital*/');
$endMarker = 'endforeach;/*END foreach($investors_query as $member)*/';
$end = strpos($template, $endMarker, (int) $start);
must($start !== false && $end !== false, 'account-template.php: calculation markers');
$closing = strpos($template, 'endif; ?>', $end);
must($closing !== false, 'account-template.php: closing endif');
$block = substr($template, $start, $closing - $start) . 'endif;';
must(!str_contains($block, '?>'), 'account-template.php: block has no PHP close tags');

$firstLine = substr_count(substr($template, 0, $start), "\n") + 1;
$lastLine  = substr_count(substr($template, 0, $closing), "\n") + 1;

$hashes = [
    'account-template.php'     => sha1_file($templateFile),
    'inc/variables.php'        => sha1_file($variablesFile),
    'inc/functions-to-use.php' => sha1_file($functionsFile),
];

$header = <<<PHP
<?php
/**
 * GENERATED by tools/extract-calc.php: do not edit by hand.
 *
 * The account calculation of the dank.capital theme (hello-theme-dank), copied
 * unchanged so the app shows exactly what the site's account page shows:
 *   - inc/variables.php (sha1 {$hashes['inc/variables.php']})
 *   - account-template.php lines {$firstLine}–{$lastLine} (sha1 {$hashes['account-template.php']})
 * It calls the theme's own count_amount_onpresent_time() and
 * net_annualized_return() from inc/functions-to-use.php.
 *
 * Included inside DankSync\Account\calculate(), which provides \$current_user
 * and keeps every variable local to that call.
 */

if (!defined('ABSPATH')) {
    exit;
}


PHP;

$pluginDir = dirname(__DIR__);
file_put_contents("$pluginDir/includes/account-calc.php", $header . $variables . "\n\n/* ---- account-template.php ---- */\n\n                " . $block . "\n");

$fingerprint = "<?php\n// GENERATED by tools/extract-calc.php: theme files the calculation was copied from.\n\nreturn " . var_export($hashes, true) . ";\n";
file_put_contents("$pluginDir/includes/theme-fingerprint.php", $fingerprint);

echo "account-calc.php: variables.php + account-template.php lines {$firstLine}–{$lastLine}\n";
foreach ($hashes as $file => $hash) {
    echo "  $file  $hash\n";
}

function must(bool $ok, string $what): void
{
    if (!$ok) {
        fwrite(STDERR, "extract failed: $what\n");
        exit(1);
    }
}
